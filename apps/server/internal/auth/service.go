// Domain errors. httpapi maps each one onto a stable HTTP status and error
// code; anything else is an internal error.
var (
	// ErrUnauthenticated covers unknown, expired or revoked credentials.
	ErrUnauthenticated = errors.New("unauthenticated")
	// ErrNotFound is returned when a resource does not exist under the
	// requesting account — deliberately indistinguishable from "belongs to
	// someone else" (no cross-account probing through this path).
	ErrNotFound = errors.New("not found")
	// ErrValidation covers malformed input that never reaches the store.
	ErrValidation = errors.New("invalid request")
	// ErrCircleHasMembers: the account owns a circle with other members and
	// must dissolve it explicitly before deleting itself (M2 invariant: a
	// populated circle is never dissolved as a side effect).
	ErrCircleHasMembers = errors.New("circle has members")
	// ErrIdentityConflict: the email already belongs to an account of the
	// other identity type (Google vs development fixture). Matching emails
	// are not proof of the same subject, so neither side may take the
	// account over.
	ErrIdentityConflict = errors.New("identity conflict")
)

// SignInInput carries everything the store needs to complete one sign-in
// atomically: resolve or create the user, register the device, revoke the
// device's previous sessions and insert the new one, with an audit row in
// the same transaction.
type SignInInput struct {
	// GoogleSub is nil for identities that did not arrive through Google
	// (the development login).
	GoogleSub   *string
	Email       string
	DisplayName string
	AvatarURL   *string
	Device      DeviceRegistration
	// Session values generated by the service; the store persists the
	// hashes, never the plaintext tokens.
	RefreshTokenHash []byte
	RefreshExpiresAt time.Time
	AccessTokenHash  []byte
	AccessExpiresAt  time.Time
	// AuditAction is the audit event name recorded with the sign-in.
	AuditAction string
}

// RefreshInput rotates the tokens of the session found by refresh hash.
type RefreshInput struct {
	CurrentRefreshHash []byte
	NewRefreshHash     []byte
	NewRefreshExpires  time.Time
	NewAccessHash      []byte
	NewAccessExpires   time.Time
}

// Store is the persistence contract of the auth domain. Implementations
// must be safe for concurrent use and must scope every read and write by
// the user given in the call — ownership is not the caller's job.
type Store interface {
	// SignIn completes the sign-in described by input and returns the final
	// user (created or existing) and the new session.
	SignIn(ctx context.Context, in SignInInput) (User, Session, error)
	// Authenticate resolves an access-token hash to its session and user,
	// rejecting revoked or expired sessions, and refreshes last_used_at.
	Authenticate(ctx context.Context, accessHash []byte) (Session, User, error)
	// Refresh rotates the token hashes of the session that currently owns
	// currentRefreshHash. Unknown, revoked or rotated-out hashes return
	// ErrUnauthenticated.
	Refresh(ctx context.Context, in RefreshInput) (Session, User, error)
	// SignOut revokes one session; revoking an already-revoked session is a
	// no-op.
	SignOut(ctx context.Context, sessionID uuid.UUID, reason string) error
	// User returns the account profile.
	User(ctx context.Context, userID uuid.UUID) (User, error)
	// UpdateProfile changes the display name.
	UpdateProfile(ctx context.Context, userID uuid.UUID, displayName string) (User, error)
	// SetLocationSharing flips the consent switch and writes the audit event
	// in the same transaction; enabledTo records the new state for the audit
	// action name.
	SetLocationSharing(ctx context.Context, userID uuid.UUID, enabled bool) (User, error)
	// DeleteUser removes the account (devices and sessions cascade) and
	// writes the deletion audit row in the same transaction.
	DeleteUser(ctx context.Context, userID uuid.UUID) error
	// ListDevices returns the account's devices with their active sessions.
	ListDevices(ctx context.Context, userID uuid.UUID) ([]DeviceWithSession, error)
	// DeleteDevice removes one device of the same account; anything else is
	// ErrNotFound.
	DeleteDevice(ctx context.Context, userID, deviceID uuid.UUID) error
}

// Service implements the auth use-cases on top of a Store.
type Service struct {
	store        Store
	google       IdentityVerifier
	googleOn     bool
	devLoginOn   bool
	auditRecords audit.Recorder
}

// NewService builds the service. google may be nil when Google sign-in is
// not configured; devLoginEnabled mounts the development sign-in (the
// config layer refuses it in production).
func NewService(store Store, google IdentityVerifier, devLoginEnabled bool, recorder audit.Recorder) *Service {
	return &Service{
		store:        store,
		google:       google,
		googleOn:     google != nil,
		devLoginOn:   devLoginEnabled,
		auditRecords: recorder,
	}
}

// GoogleEnabled reports whether Google sign-in is usable on this server.
func (s *Service) GoogleEnabled() bool { return s.googleOn }

// DevLoginEnabled reports whether the development login is mounted.
func (s *Service) DevLoginEnabled() bool { return s.devLoginOn }

// SignInWithGoogle verifies a Google ID token and completes the sign-in.
func (s *Service) SignInWithGoogle(ctx context.Context, idToken string, device DeviceRegistration) (User, SessionTokens, error) {
	if !s.googleOn || s.google == nil {
		return User{}, SessionTokens{}, ErrGoogleNotConfigured
	}
	if strings.TrimSpace(idToken) == "" {
		return User{}, SessionTokens{}, fmt.Errorf("%w: idToken is empty", ErrValidation)
	}
	if err := validateDevice(device); err != nil {
		return User{}, SessionTokens{}, err
	}
	identity, err := s.google.Verify(ctx, idToken)
	if err != nil {
		return User{}, SessionTokens{}, fmt.Errorf("%w: google token rejected", ErrUnauthenticated)
	}

	sub := identity.Sub
	name := identity.Name
	if name == "" {
		name = emailLocalPart(identity.Email)
	}
	return s.completeSignIn(ctx, SignInInput{
		GoogleSub:   &sub,
		Email:       identity.Email,
		DisplayName: name,
		AvatarURL:   nilIfEmpty(identity.Picture),
		Device:      device,
		AuditAction: audit.ActionSignIn,
	})
}

// DevSignIn signs in an arbitrary email — the audited development fixture
// that only exists outside production (see ADR 0002).
func (s *Service) DevSignIn(ctx context.Context, email, displayName string, device DeviceRegistration) (User, SessionTokens, error) {
	if !s.devLoginOn {
		return User{}, SessionTokens{}, fmt.Errorf("%w: dev login is not mounted", ErrNotFound)
	}
	email = strings.ToLower(strings.TrimSpace(email))
	if !validEmail(email) {
		return User{}, SessionTokens{}, fmt.Errorf("%w: email is invalid", ErrValidation)
	}
	if displayName == "" {
		displayName = emailLocalPart(email)
	}
	if err := validateDevice(device); err != nil {
		return User{}, SessionTokens{}, err
	}
	return s.completeSignIn(ctx, SignInInput{
		Email:       email,
		DisplayName: displayName,
		Device:      device,
		AuditAction: audit.ActionDevSignIn,
	})
}

func (s *Service) completeSignIn(ctx context.Context, in SignInInput) (User, SessionTokens, error) {
	access, accessHash, err := newToken()
	if err != nil {
		return User{}, SessionTokens{}, fmt.Errorf("generate access token: %w", err)
	}
	refresh, refreshHash, err := newToken()
	if err != nil {
		return User{}, SessionTokens{}, fmt.Errorf("generate refresh token: %w", err)
	}
	now := time.Now().UTC()
	in.AccessTokenHash = accessHash
	in.AccessExpiresAt = now.Add(AccessTokenTTL)
	in.RefreshTokenHash = refreshHash
	in.RefreshExpiresAt = now.Add(RefreshTokenTTL)

	user, _, err := s.store.SignIn(ctx, in)
	if err != nil {
		return User{}, SessionTokens{}, err
	}
	return user, SessionTokens{
		AccessToken:      access,
		RefreshToken:     refresh,
		AccessExpiresAt:  in.AccessExpiresAt,
		RefreshExpiresAt: in.RefreshExpiresAt,
	}, nil
}

// Refresh rotates the token pair of the session owning refreshToken.
func (s *Service) Refresh(ctx context.Context, refreshToken string) (SessionTokens, error) {
	if refreshToken == "" {
		return SessionTokens{}, fmt.Errorf("%w: refreshToken is empty", ErrValidation)
	}
	access, accessHash, err := newToken()
	if err != nil {
		return SessionTokens{}, fmt.Errorf("generate access token: %w", err)
	}
	refresh, refreshHash, err := newToken()
	if err != nil {
		return SessionTokens{}, fmt.Errorf("generate refresh token: %w", err)
	}
	now := time.Now().UTC()
	_, _, err = s.store.Refresh(ctx, RefreshInput{
		CurrentRefreshHash: hashToken(refreshToken),
		NewRefreshHash:     refreshHash,
		NewRefreshExpires:  now.Add(RefreshTokenTTL),
		NewAccessHash:      accessHash,
		NewAccessExpires:   now.Add(AccessTokenTTL),
	})
	if err != nil {
		return SessionTokens{}, err
	}
	return SessionTokens{
		AccessToken:      access,
		RefreshToken:     refresh,
		AccessExpiresAt:  now.Add(AccessTokenTTL),
		RefreshExpiresAt: now.Add(RefreshTokenTTL),
	}, nil
}

// Authenticate is the middleware entry point: it resolves an access token
// to its session and user.
func (s *Service) Authenticate(ctx context.Context, accessToken string) (Session, User, error) {
	if accessToken == "" {
		return Session{}, User{}, fmt.Errorf("%w: missing token", ErrUnauthenticated)
	}
	return s.store.Authenticate(ctx, hashToken(accessToken))
}

// SignOut revokes the session that issued the request.
func (s *Service) SignOut(ctx context.Context, session Session) error {
	if err := s.store.SignOut(ctx, session.ID, "user_signout"); err != nil {
		return err
	}
	audit.BestEffort(ctx, s.auditRecords, audit.Event{
		ActorUserID: session.UserID,
		Action:      audit.ActionSignOut,
		Detail:      map[string]any{"session_id": session.ID.String(), "device_id": session.DeviceID.String()},
	})
	return nil
}

// Profile returns the account of the authenticated user.
func (s *Service) Profile(ctx context.Context, userID uuid.UUID) (User, error) {
	return s.store.User(ctx, userID)
}

// UpdateProfile validates and applies a display-name change.
func (s *Service) UpdateProfile(ctx context.Context, userID uuid.UUID, displayName string) (User, error) {
	displayName = strings.TrimSpace(displayName)
	if displayName == "" || len([]rune(displayName)) > 80 {
		return User{}, fmt.Errorf("%w: displayName must be 1-80 characters", ErrValidation)
	}
	return s.store.UpdateProfile(ctx, userID, displayName)
}

// SetLocationSharing is THE consent switch of the privacy foundation. It is
// always the data subject's own account; every change is audited in the
// same transaction that flips the flag.
func (s *Service) SetLocationSharing(ctx context.Context, userID uuid.UUID, enabled bool) (User, error) {
	return s.store.SetLocationSharing(ctx, userID, enabled)
}

// DeleteAccount removes the account and everything hanging off it.
func (s *Service) DeleteAccount(ctx context.Context, userID uuid.UUID) error {
	return s.store.DeleteUser(ctx, userID)
}

// ListDevices lists the account's devices; currentSessionID marks which
// session served the call.
func (s *Service) ListDevices(ctx context.Context, userID uuid.UUID, currentSessionID uuid.UUID) ([]DeviceWithSession, error) {
	devices, err := s.store.ListDevices(ctx, userID)
	if err != nil {
		return nil, err
	}
	for i := range devices {
		if devices[i].Session != nil && devices[i].Session.ID == currentSessionID {
			devices[i].Current = true
		}
	}
	return devices, nil
}

// RevokeDevice deletes one of the account's devices and cascades its
// sessions. Revoking the device of the calling session signs the caller
// out, which is intended ("đăng xuất thiết bị này").
func (s *Service) RevokeDevice(ctx context.Context, userID, deviceID uuid.UUID) error {
	if err := s.store.DeleteDevice(ctx, userID, deviceID); err != nil {
		return err
	}
	audit.BestEffort(ctx, s.auditRecords, audit.Event{
		ActorUserID: userID,
		Action:      audit.ActionDeviceRevoked,
		Detail:      map[string]any{"device_id": deviceID.String()},
	})
	return nil
}

// validateDevice enforces the contract's device constraints.
func validateDevice(d DeviceRegistration) error {
	d.ClientDeviceID = strings.TrimSpace(d.ClientDeviceID)
	if len(d.ClientDeviceID) < 8 || len(d.ClientDeviceID) > 64 {
		return fmt.Errorf("%w: clientDeviceId must be 8-64 characters", ErrValidation)
	}
	if len(d.Name) > 120 {
		return fmt.Errorf("%w: device name too long", ErrValidation)
	}
	if p := strings.TrimSpace(d.Platform); p != "" && p != "android" {
		return fmt.Errorf("%w: unsupported platform %q", ErrValidation, p)
	}
	if len(d.AppVersion) > 40 {
		return fmt.Errorf("%w: appVersion too long", ErrValidation)
	}
	return nil
}

func validEmail(email string) bool {
	if email == "" || len(email) > 254 {
		return false
	}
	at := strings.IndexByte(email, '@')
	if at <= 0 || at == len(email)-1 {
		return false
	}
	if strings.Count(email, "@") != 1 {
		return false
	}
	for _, r := range email {
		if r > unicode.MaxASCII || !unicode.IsPrint(r) {
			return false
		}
	}
	return true
}

// emailLocalPart derives a default display name ("mai.anh" from
// "mai.anh@example.com") for identities that arrive without one.
func emailLocalPart(email string) string {
	if at := strings.IndexByte(email, '@'); at > 0 {
		return email[:at]
	}
	return email
}

func nilIfEmpty(s string) *string {
	if s == "" {
		return nil
	}
	return &s
}
